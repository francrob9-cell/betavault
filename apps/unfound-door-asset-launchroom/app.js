els.assetGrid.addEventListener("click", async (event) => {
  const reviewLink = event.target.closest("[data-action='select-review']");
  if (reviewLink) {
    event.preventDefault();
    selectAssetForReview(reviewLink.dataset.id);
    return;
  }

  const button = event.target.closest("button");
  const card = event.target.closest(".asset-card");
  if (!button && card) {
    selectAssetForReview(card.dataset.id);
    return;
  }

  if (!button) return;
  const asset = state.assets.find((item) => item.id === button.dataset.id);
  if (!asset) return;

  if (button.dataset.action === "select") {
    selectAssetForReview(asset.id);
  }

  if (button.dataset.action === "copy") {
    await navigator.clipboard.writeText(fullSizeUrl(asset));
    showToast("Full size asset URL copied");
  }

  if (button.dataset.action === "open-full") {
    window.open(fullSizeUrl(asset), "_blank", "noreferrer");
  }
});

