function cropCanvasBlob(canvas) {
  return new Promise((resolve) => {
    canvas.toBlob((blob) => resolve(blob), "image/jpeg", 0.92);
  });
}

function platformPostUrl(presetKey) {
  if (presetKey === "tiktok") return "https://www.tiktok.com/upload";
  if (presetKey === "facebook-feed") return "https://www.facebook.com/";
  if (presetKey === "youtube-thumb") return "https://www.youtube.com/upload";
  if (presetKey === "instagram-square" || presetKey === "instagram-feed" || presetKey === "stories") {
    return "https://www.instagram.com/";
  }
  return "";
}

