function cropForAsset(asset) {
  if (!asset.crop) asset.crop = defaultCrop();
  return asset.crop;
}

function clampCrop(crop) {
  crop.w = Math.max(10, Math.min(100, Number(crop.w) || 10));
  crop.h = Math.max(10, Math.min(100, Number(crop.h) || 10));
  crop.x = Math.max(0, Math.min(100 - crop.w, Number(crop.x) || 0));
  crop.y = Math.max(0, Math.min(100 - crop.h, Number(crop.y) || 0));
  return crop;
}

function applyCropPreset(crop, preset) {
  crop.preset = preset;
  if (preset === "free") return clampCrop(crop);

  const presetConfig = CROP_PRESETS[preset];
  if (!presetConfig?.ratio) return clampCrop(crop);

  const image = document.querySelector("#reviewCropImage");
  const imageRatio = image?.naturalWidth && image?.naturalHeight ? image.naturalWidth / image.naturalHeight : 1;
  const currentCenterX = crop.x + crop.w / 2;
  const currentCenterY = crop.y + crop.h / 2;
  let nextW = Math.min(crop.w, 86);
  let nextH = (imageRatio * nextW) / presetConfig.ratio;

  if (nextH > 100) {
    nextH = 86;
    nextW = (nextH * presetConfig.ratio) / imageRatio;
  }

  crop.w = Math.min(100, nextW);
  crop.h = Math.min(100, nextH);
  crop.x = currentCenterX - crop.w / 2;
  crop.y = currentCenterY - crop.h / 2;
  return clampCrop(crop);
}

function openInNewTab(url) {
  const link = document.createElement("a");
  link.href = url;
  link.target = "_blank";
  link.rel = "noopener noreferrer";
  document.body.appendChild(link);
  link.click();
  link.remove();
}

function isPhotoAsset(asset) {
  return asset.type === "photo" && !String(asset.src || "").toLowerCase().match(/\.(mp4|mov|webm|m4v)(\?|$)/);
}

function isVideoAsset(asset) {
  return asset.type === "video" || String(asset.src || "").toLowerCase().match(/\.(mp4|mov|webm|m4v)(\?|$)/);
}

function mediaMarkup(asset, className = "", options = {}) {
  if (!asset) return "";
  const classAttr = className ? ` class="${className}"` : "";
  const loading = options.loading || "lazy";
  const fetchPriority = options.fetchPriority ? ` fetchpriority="${options.fetchPriority}"` : "";
  return isVideoAsset(asset)
    ? `<video${classAttr} src="${asset.src}" controls playsinline preload="metadata"></video>`
    : `<img${classAttr} src="${asset.src}" alt="${escapeHtml(asset.name)}" loading="${loading}" decoding="async"${fetchPriority} />`;
}

