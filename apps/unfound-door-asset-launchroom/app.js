async function postSelectedCrop() {
  const cropOutput = selectedCropCanvas();
  if (!cropOutput) return;

  const fileName = cropFileName(cropOutput.asset, cropOutput.preset);
  const blob = await cropCanvasBlob(cropOutput.canvas);
  if (!blob) {
    showToast("Could not prepare crop for posting");
    return;
  }

  const file = new File([blob], fileName, { type: "image/jpeg" });
  if (navigator.canShare?.({ files: [file] })) {
    await navigator.share({
      files: [file],
      title: `${cropOutput.asset.name} - ${cropOutput.preset.label}`,
      text: `Ready for ${cropOutput.preset.label}`,
    });
    showToast("Crop opened in share sheet");
    return;
  }

  downloadCanvas(cropOutput.canvas, fileName);
  const postUrl = platformPostUrl(cropForAsset(cropOutput.asset).preset);
  if (postUrl) {
    openInNewTab(postUrl);
    showToast(`Crop downloaded. Upload it on ${cropOutput.preset.label}.`);
  } else {
    showToast("Crop downloaded. Choose a social preset to open a platform.");
  }
}

